//Arthimetic Operators
let a = 10;
let b = 4;
console.log("a =", a)
console.log("b =", b)
//addition and subtraction
console.log("a - b = ", a-b)
console.log("a + b = ", a+b)
//divsion and multiplication
console.log("a / b = ", a/b)
console.log("a * b = ", a*b)
//exponansional and modulus(remainder)
console.log("a ** b = ", a**b)
console.log("a % b = ", a%b)
//increment and decrement
console.log("++a = ", ++a)
console.log("a++ = ", a++)
console.log("--a = ", --a)
console.log("a-- = ", a--)
console.log("a = ", a)
console.log("a-- = ", a--)

// Assignment Operators
let c = 12;
c += 5 // same as c = c + 5
console.log("c is now =", c)
c -= 5 // same as c = c - 5
console.log("c is now =", c)
c /= 5 // same as c = c / 5
console.log("c is now =", c)
c *= 5 // same as c = c * 5
console.log("c is now =", c)
c **= 5 // same as c = c ** 5
console.log("c is now =", c)

// Comparison Operators 
let comp1 = 6;
let comp2 = "6";
console.log("comp1 =", comp1)
console.log("comp2 =", comp2)
console.log("comp1 == comp2 is", comp1 == comp2)
console.log("comp1 != comp2 is", comp1 != comp2)
console.log("comp1 === comp2 is", comp1 === comp2)
console.log("comp1 !== comp2 is", comp1 !== comp2)
console.log("comp1 > comp2 is", comp1 > comp2)

//Logical Operators
let x = 5;
let y = 6;
console.log(x > y && x == 5)
console.log(x < y || x != 5)
console.log("not false gives:", !false)
console.log("not true gives:", !true)

